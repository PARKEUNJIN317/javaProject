package exam.ojdbc;

public class ProductVO {
	private String no;
	private String name;
	private String maker;
	private String color;
	
	public ProductVO() {}

	public ProductVO(String no, String name, String maker, String color) {
		this.no = no;
		this.name = name;
		this.maker = maker;
		this.color = color;
	}

	public String getNo() {
		return no;
	}

	public void setNo(String no) {
		this.no = no;
	}

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}

	public String getMaker() {
		return maker;
	}

	public void setMaker(String maker) {
		this.maker = maker;
	}

	public String getColor() {
		return color;
	}

	public void setColor(String color) {
		this.color = color;
	}

	


	
	
	
	
	
	

}
